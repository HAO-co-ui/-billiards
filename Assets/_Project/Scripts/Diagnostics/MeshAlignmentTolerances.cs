namespace Billiards.Diagnostics
{
    /// <summary>
    /// 比对与几何自检的**容差单值源**（铁律 16：同一不变量的检查/常量必须单点实现）。
    ///
    /// **为什么需要它**：这些容差原本只有 <c>TableIntegrityValidator</c> 是真源，
    /// 而 EditMode 测试把它们**复制成字面量多处**（<c>TableConfigTests</c>、<c>MeshAlignmentSensitivityTests</c>、
    /// <c>ModelOrientationTests</c>），注释写着"必须与 TableIntegrityValidator 一致" ——
    /// **靠注释维持一致 = 一定会分叉**。现收敛到本类，Editor 与 Tests 共同引用同一份值。
    ///
    /// ⚠ **不是所有测试里的浮点容差都该进本类。** 判据是「**它是否需要与别处保持一致**」：
    ///  · 需要一致（跨文件表达同一判据）⇒ 进本类（<see cref="IndexAligned"/>、<see cref="Bounds"/>、
    ///    <see cref="TransformIdentity"/>、三层度量）。
    ///  · 仅在本文件内自洽的经验阈值（如某些审计专用上界）⇒ **保持本地**，并在该处注明理由。
    /// **把语义不同的容差硬塞进同一个常量，是"看起来单源"的假收敛。**
    ///
    /// **容差策略**（采纳独立复核 D2-T02A 的实测结论）：
    /// 顺序无关（集合/最近邻）比对下，全量镜像/180° 旋转与真值只差
    /// 镜像 x→−x = 4.74e-4 m、镜像 y = 1.04e-4 m、180° 绕竖轴 = 4.73e-4 m ⇒ **1 mm 容差会被"骗过去"**。
    /// 因此分层策略是：
    ///  ① 主判据（决定成败）= **索引对齐 + 逐字段**比对（<see cref="IndexAligned"/>）；
    ///  ② 手性/绕向自检（不依赖基线）= CHR-01「袋口局部手性符号」/ CHR-02「库边链绕向」；
    ///  ③ AXL-02 世界包围盒用 x 向不对称（0.277 mm）钉手性（<see cref="Bounds"/>）；
    ///  ④ 网格对齐为**三层**（L1 面点 / L2 边距 / L3 顶点比值），三层**各自有盲区**，
    ///     **谁都不作唯一位移判据**；单点位移威胁由 ① 兜底。
    /// </summary>
    public static class MeshAlignmentTolerances
    {
        /// <summary>① 主判据容差：索引对齐逐字段比对，1e-5 m（独立复核建议值）。</summary>
        public const float IndexAligned = 1e-5f;

        /// <summary>③ 世界包围盒容差（= 转换链推导期望）：0.1 mm。缩放/旋转错误会远超此值。</summary>
        public const float Bounds = 1e-4f;

        /// <summary>
        /// **几何自检容差 = 1e-5**：同一几何量的两种算法／两种表示必须一致。
        /// 覆盖：轴修正行列式 det = +1（保手性）、纯旋转保距、分量式 API 与四元数式 API 等价、
        /// 判决量（角袋 x 向不对称）复现。
        ///
        /// **为什么与 <see cref="IndexAligned"/> 分开**：两者数值同为 1e-5，但**语义不同** ——
        /// `IndexAligned` 是"两份数据必须逐字段一致"，本项是"同一个几何量的两种算法必须一致"。
        /// 混用会让将来任一方调整时误伤另一方。**数值巧合不是合并的理由。**
        /// </summary>
        public const float TransformIdentity = 1e-5f;

        /// <summary>
        /// **L1（必要条件层）** 端点 → 最近**面内点**（含内部与边）的容差 = **1e-4 m**。
        /// 只验"端点落在网格面上"；**对足迹内滑动盲**（点仍在网格内），
        /// 但**对掉出网格（袋孔、掉出外轮廓）敏感** —— **不作位移判据**。
        /// </summary>
        public const float L1SurfacePoint = 1e-4f;

        /// <summary>
        /// **L2（高灵敏层）** 端点 → 最近**网格边** 的容差 = **5 µm**。
        /// 推导：正确数据 188 端点 → 最近边 max = **0.18 µm**；float32 在 |坐标|≈1.3 m 处 ULP ≈ **0.155 µm**；
        /// 噪声底 = max(0.18, 0.16) ≈ **0.18 µm** ⇒ 5 µm ≈ **28× 底噪**。
        /// **盲区**：**沿边方向滑动 ⇒ 点仍在该边上 ⇒ 距离恒 ≈0，无论滑多远** ⇒ 不作唯一位移判据，靠 L3 兜。
        /// 备选 2 µm 仅在"确认网格不再重导出"前提下可用；本轮**不收紧**（网格重导出是真实可能性，收紧会引入假阳性）。
        /// </summary>
        public const float L2EdgeDistance = 5e-6f;

        /// <summary>
        /// **L3（全向层）** 端点→最近顶点 距离 / 最近三角形最长边 的**比值**上界。
        /// 取值依据：实测观测最坏比值 = 0.2613 / 5.455 = **0.0479**；取 **2× 余量** ⇒ k = **0.0958**（该测量是确定性的）。
        /// 阈值 T = k × L_local ≈ **0.52 mm**（≈ 现状 0.5 mm），检出下限 ≈ **0.40~0.75 mm**。
        /// **理论硬上界 0.5**（点落在边中点时距离 = 0.5·L_local）—— 留档供将来换网格对照，
        /// **不得取 0.5**（永不假阳性＝灵敏度最差）。
        /// **盲区**：**周期性盲带**（δ 增大时点落到另一顶点附近，距离回落）。
        /// 实测：对**整段/区域刚性位移**无上盲带（仅 ≤~0.4 mm 底噪带）；对**单点位移**存在盲带（本次采样最高至 12.4 mm）。
        /// 单点位移这一威胁**由主判据（索引对齐，1e-5 m）覆盖**。
        /// </summary>
        public const float L3VertexRatio = 0.0958f;

        /// <summary>L3 的理论硬上界（留档）：点落在边中点时距离 = 0.5·L_local。不得用作阈值。</summary>
        public const float L3TheoreticalBound = 0.5f;

        /// <summary>实测基线（顶点度量 0.2613 mm）—— 输出中显示用。</summary>
        public const float MeasuredVertexBaseline = 0.0002613f;
    }
}
